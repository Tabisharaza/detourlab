#!/usr/bin/env node
import { formatInputError } from '../src/file-input.js';
import { verifyReview } from './review-verification.js';

const usage = `DetourLab read-only review packet verification

Usage: node scripts/verify-review.js packet-directory [options]

  --compare-outcomes  Explicitly allow unknown or mismatched implementation
                     identity; original implementation remains unverified
  --json             Print a machine-readable verification result
  --help             Show help without reading input

The directory must contain the original bundle.json (at most 8 MiB) and
REVIEW.md (at most 1 MiB). Both files must be regular UTF-8 files, not symlinks.
The packet root must be a real directory. No files are written or uploaded.
Each option may be supplied once. Use ./ for paths beginning with a dash.
Embedded input and policy are rerun once under this trusted checkout, with
existing simulation budgets. Complete generated bytes must match both files.
Default verification also requires a matching implementation fingerprint.
Comparison mode never verifies which implementation originally ran the packet.
No policy overrides, signature verification, or source-revision authentication.
Exit 0: verified packet, supplied policy passed or no policy was evaluated.
Exit 1: verified packet, embedded acceptance policy failed.
Exit 2: invalid input, mismatch, failed simulation or filesystem failure.
Hashes are not signatures; reproducibility is not real-world validity.`;

function argumentsFor(args) {
  if (args.includes('--help')) return { help: true };
  let directory;
  const flags = new Set();
  for (const arg of args) {
    if (arg === '--json' || arg === '--compare-outcomes') {
      if (flags.has(arg)) throw new Error(`${arg} may only be supplied once.`);
      flags.add(arg);
    } else if (arg.startsWith('-')) throw new Error(`Unknown option: ${arg}`);
    else {
      if (directory !== undefined) throw new Error('Only one packet directory may be supplied.');
      directory = arg;
    }
  }
  if (directory === undefined || !directory.trim()) throw new Error('A packet directory is required. Use --help for usage.');
  return { directory, compareOutcomes: flags.has('--compare-outcomes'), json: flags.has('--json') };
}

try {
  const options = argumentsFor(process.argv.slice(2));
  if (options.help) console.log(usage);
  else {
    const result = await verifyReview(options.directory, { compareOutcomes: options.compareOutcomes });
    if (options.json) console.log(JSON.stringify(result, null, 2));
    else {
      console.log(result.mode === 'exact-implementation'
        ? 'Exact packet reproduction verified against this checkout.'
        : 'Packet outcomes reproduced under this checkout; original implementation remains unverified.');
      console.log(`Policy: ${result.policyVerdict.toUpperCase().replace('-', ' ')}.`);
      console.log('Fingerprints are not signatures; authorship and source revision are not authenticated.');
    }
    if (result.policyVerdict === 'failed') process.exitCode = 1;
  }
} catch (error) {
  console.error(`DetourLab: ${formatInputError(error)}`);
  process.exitCode = 2;
}
